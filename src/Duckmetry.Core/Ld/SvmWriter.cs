    /// <summary>
    /// The [BASIC] block holds five 0..1 slider positions derived from the real setup.
    /// These are the game's convenience "balance" sliders, not recorded settings, so
    /// they are only written when we can compute something meaningful.
    /// </summary>
    private static void AppendBasicSliders(StringBuilder sb, Dictionary<string, SetupEntry> setup)
    {
        // The game derives these itself; without a documented formula we omit the
        // block rather than emit numbers that would silently misrepresent the setup.
        _ = setup;
    }

    /// <summary>
    /// Converts UPPER_SNAKE to PascalCase, preserving digits and existing capitals.
    /// </summary>
    private static string PascalCase(string upperSnake)
    {
        var sb = new StringBuilder(upperSnake.Length);
        foreach (var token in upperSnake.Split('_', StringSplitOptions.RemoveEmptyEntries))
        {
            if (token.Length == 0) continue;
            // Capitalise the first letter and lowercase the rest, so "SLOWBUMP" and
            // "FASTREBOUND" become "Slowbump"/"Fastrebound".
            sb.Append(char.ToUpperInvariant(token[0]));
            if (token.Length > 1) sb.Append(token[1..].ToLowerInvariant());
        }
        return sb.ToString();
    }

    /// <summary>
    /// The integer the .svm stores: the setting's index. Falls back to parsing the
    /// leading integer of the display string when <c>value</c> is absent.
    /// </summary>
    private static int IndexOf(JsonElement entry)
    {
        if (entry.TryGetProperty("value", out var v))
        {
            if (v.ValueKind == JsonValueKind.Number && v.TryGetInt32(out var i)) return i;
            if (v.ValueKind == JsonValueKind.String &&
                int.TryParse(v.GetString(), NumberStyles.Integer, CultureInfo.InvariantCulture, out var s))
            {
                return s;
            }
        }
        if (entry.TryGetProperty("stringValue", out var sv) &&
            sv.ValueKind == JsonValueKind.String)
        {
            var text = sv.GetString();
            if (!string.IsNullOrEmpty(text))
            {
                var digits = new string(text.TakeWhile(c => char.IsDigit(c) || c == '-').ToArray());
                if (int.TryParse(digits, out var d)) return d;
            }
        }
        return 0;
    }

    /// <summary>
    /// The trailing "//display" comment. The game shows this text next to the slider,
    /// so the recorded human-readable value is what belongs there.
    /// </summary>
    private static string CommentOf(JsonElement entry)
    {
        if (entry.TryGetProperty("stringValue", out var sv) && sv.ValueKind == JsonValueKind.String)
        {
            var s = sv.GetString();
            if (!string.IsNullOrWhiteSpace(s) && s != "N/A") return s.Trim();
        }
        return string.Empty;
    }

    /// <summary>
    /// Recovers the car class from a Vehicle string of the form "Name (CLASS)".
    /// </summary>
    private static string ExtractCarClass(string? vehicle)
    {
        if (string.IsNullOrWhiteSpace(vehicle)) return string.Empty;
        int open = vehicle.LastIndexOf('(');
        int close = vehicle.LastIndexOf(')');
        if (open < 0 || close <= open + 1) return string.Empty;
        return vehicle[(open + 1)..close].Trim();
    }

    /// <summary>
    /// Flattens the CarSetup JSON into a dictionary keyed by the bare (prefix-stripped)
    /// setting name, so lookups do not have to care about VM_/WM_ separately.
    /// </summary>
    private static Dictionary<string, SetupEntry> ParseSetup(string? rawJson)
    {
        var result = new Dictionary<string, SetupEntry>(StringComparer.Ordinal);
        if (string.IsNullOrWhiteSpace(rawJson)) return result;

        try
        {
            using var doc = JsonDocument.Parse(rawJson);
            if (doc.RootElement.ValueKind != JsonValueKind.Object) return result;

            foreach (var prop in doc.RootElement.EnumerateObject())
            {
                if (prop.Value.ValueKind != JsonValueKind.Object) continue;
                string key = prop.Name;
                if (key.StartsWith("VM_", StringComparison.Ordinal)) key = "VM_" + key[3..];
                else if (key.StartsWith("WM_", StringComparison.Ordinal)) key = "WM_" + key[3..];

                // A JsonElement is only valid while its JsonDocument is alive, so the
                // values we need are copied out now rather than keeping the element.
                result[key] = new SetupEntry(IndexOf(prop.Value), CommentOf(prop.Value));
            }
        }
        catch (JsonException)
        {
            return new Dictionary<string, SetupEntry>(StringComparer.Ordinal);
        }
        return result;
    }

    /// <summary>
    /// The two values the .svm needs from one setup entry: the integer index the game
    /// stores, and the human-readable text it shows beside the slider.
    /// </summary>
    private readonly record struct SetupEntry(int Value, string Comment);
}
