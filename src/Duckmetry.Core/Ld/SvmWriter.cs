/// <summary>
/// Writes the car's setup in the game's own ".svm" (Setup Variable Markup) format, the
/// same format the game reads from and writes to its vehicle setup folders.
/// </summary>
/// <remarks>
/// <para>
/// Verified against log+example/GT3_FM_Balanced_Laguna_gemini_race.svm (a genuine
/// game-written file). Structure:
///
/// <code>
/// VehicleClassSetting="Ford_Mustang_LMGT3 GT3 WEC2025"
/// UpgradeSetting=(2147870,0,0,0)
/// //VEH=...            (commented metadata; the game tolerates its absence)
///
/// [GENERAL]
/// Notes=""
/// Symmetric=1
/// FuelSetting=100//1.01
/// ...one "&lt;PascalCaseName&gt;Setting=&lt;index&gt;//&lt;display comment&gt;" per line
/// </code>
///
/// </para>
/// <para>
/// Mapping from the the game <c>CarSetup</c> JSON:
/// <list type="bullet">
///   <item><description>keys are UPPER_SNAKE (<c>VM_REAR_WING</c>); the file uses
///   PascalCase + "Setting" (<c>RWSetting</c>), so each underscore-separated token is
///   capitalised.</description></item>
///   <item><description>the <c>VM_</c> prefix marks vehicle-wide settings, the
///   <c>WM_</c> prefix marks per-corner ones. Per-corner names embed the corner
///   (<c>CAMBER-W_FL</c>); in the .svm the corner is implied by the enclosing section
///   ([FRONTLEFT] etc.) and the suffix is dropped.</description></item>
///   <item><description>the written value is the numeric <c>value</c> field - the
///   setting's index, not the display string. Confirmed against the reference where
///   <c>FW</c>=0 and <c>EngineMixture</c>=1 both round-trip exactly.</description></item>
/// </list>
/// Settings that differ only per corner still need an explicit name inside their
/// section, so the corner prefix is retained as part of the name when the .svm name
/// alone would be ambiguous.
/// </para>
/// </remarks>
public static class SvmWriter
{
    /// <summary>Section name for each corner, in .svm order.</summary>
    private static readonly (string JsonSuffix, string Section)[] CornerSections =
    {
        ("_FL", "FRONTLEFT"),
        ("_FR", "FRONTRIGHT"),
        ("_RL", "REARLEFT"),
        ("_RR", "REARRIGHT")
    };

    /// <summary>
    /// Writes the setup as a .svm file. Returns false if there is no usable setup data.
    /// </summary>
    public static bool TryWriteFile(string filePath, SessionMetadata metadata)
    {
        var setup = ParseSetup(metadata.RawSetupJson);
        if (setup.Count == 0) return false;

        var sb = new StringBuilder(16 * 1024);
        sb.Append(CrLf);

        // ---- Header ----------------------------------------------------------
        string vehicleClass = ExtractCarClass(metadata.Vehicle);
        // The game's VehicleClassSetting is the car-class id, e.g.
        // "Ford_Mustang_LMGT3 GT3 WEC2025". the game records it in CarName/CarClass, which
        // this project folds into Vehicle as "<name> (<class>)" - recover the class
        // from the parenthesised tail when that is how it was stored.
        if (!string.IsNullOrWhiteSpace(vehicleClass))
        {
            sb.Append("VehicleClassSetting=\"").Append(vehicleClass).Append('"').Append(CrLf);
        }
        sb.Append("UpgradeSetting=(0,0,0,0)").Append(CrLf);
        sb.Append("//Generated by Duckmetry from the recorded session setup").Append(CrLf);
        sb.Append(CrLf);

        // ---- Vehicle-wide settings -------------------------------------------
        // Vehicle-wide keys carry no per-corner suffix, so they are grouped by the
        // .svm section they belong to via the lookup table below.
        foreach (var (section, entries) in GroupVehicleWide(setup))
        {
            AppendSection(sb, section, entries);
        }

        // ---- Per-corner settings ---------------------------------------------
        foreach (var corner in CornerSections)
        {
            var entries = new List<(string Name, int Value, string Comment)>();
            foreach (var (key, entry) in setup)
            {
                if (key.StartsWith("WM_", StringComparison.Ordinal) &&
                    key.EndsWith(corner.JsonSuffix, StringComparison.Ordinal))
                {
                    // "WM_CAMBER-W_FL" -> strip "WM_" and the "-W_FL" corner marker,
                    // leaving "CAMBER". The -W- marker is a wheel/suspension prefix and
                    // must not reach the .svm name, where the section already implies it.
                    var bare = key[3..^corner.JsonSuffix.Length];
                    int wheelMarker = bare.LastIndexOf("-W", StringComparison.Ordinal);
                    if (wheelMarker >= 0) bare = bare[..wheelMarker];
                    var name = CornerName(bare) ?? PascalCase(bare);
                    if (name.Length == 0) continue;
                    entries.Add((name, entry.Value, entry.Comment));
                }
            }
            if (entries.Count > 0) AppendSection(sb, corner.Section, entries);
        }

        // ---- Derived [BASIC] sliders ------------------------------------------
        AppendBasicSliders(sb, setup);

        File.WriteAllText(filePath, sb.ToString(), new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
        return true;
    }

    private const string CrLf = "\r\n";

    private static void AppendSection(
        StringBuilder sb, string section, List<(string Name, int Value, string Comment)> entries)
    {
        sb.Append('[').Append(section).Append(']').Append(CrLf);
        foreach (var (name, value, comment) in entries)
        {
            sb.Append(name).Append("Setting=").Append(value.ToString(CultureInfo.InvariantCulture));
            if (!string.IsNullOrEmpty(comment)) sb.Append("//").Append(comment);
            sb.Append(CrLf);
        }
        sb.Append(CrLf);
    }

